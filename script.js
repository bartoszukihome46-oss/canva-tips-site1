const originalTextNodes = new WeakMap();
let currentLanguage = "en";

try {
    currentLanguage = window.localStorage.getItem("canvaTipsLanguage") || "en";
} catch (error) {
    currentLanguage = "en";
}

function getLocalizedText(text, language = currentLanguage) {
    if (language !== "pl") {
        return text;
    }

    return languageTranslations.pl[text] || text;
}

function translatePageText(language) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            const parent = node.parentElement;

            if (!node.nodeValue.trim() || (parent && parent.closest(".language-toggle"))) {
                return NodeFilter.FILTER_REJECT;
            }

            return NodeFilter.FILTER_ACCEPT;
        }
    });

    const textNodes = [];
    let node = walker.nextNode();

    while (node) {
        textNodes.push(node);
        node = walker.nextNode();
    }

    textNodes.forEach((textNode) => {
        if (!originalTextNodes.has(textNode)) {
            originalTextNodes.set(textNode, textNode.nodeValue);
        }

        const originalText = originalTextNodes.get(textNode);
        const textKey = originalText.trim();
        const translatedText = getLocalizedText(textKey, language);
        textNode.nodeValue = originalText.replace(textKey, translatedText);
    });
}

/* Color swatches */
const colorSwatches = document.querySelectorAll(".color-swatch");

async function copyColor(button) {
    const color = button.dataset.color;

    try {
        await navigator.clipboard.writeText(color);
        button.dataset.copied = "true";
        const label = button.querySelector(".color-copy");

        if (label) {
            label.textContent = getLocalizedText("Copied");
        }

        window.setTimeout(() => {
            button.dataset.copied = "false";
            if (label) {
                label.textContent = getLocalizedText("Copy");
            }
        }, 1400);
    } catch (error) {
        button.dataset.copied = "false";
    }
}

colorSwatches.forEach((button) => {
    button.addEventListener("click", () => {
        copyColor(button);
    });
});

/* Scroll progress */
const progressFill = document.querySelector(".scroll-progress span");

function updateScrollProgress() {
    if (!progressFill) {
        return;
    }

    const scrollableHeight = document.documentElement.scrollHeight - window.innerHeight;
    const progress = scrollableHeight > 0 ? window.scrollY / scrollableHeight : 0;
    progressFill.style.transform = `scaleX(${Math.min(progress, 1)})`;
}

updateScrollProgress();
window.addEventListener("scroll", updateScrollProgress, { passive: true });
window.addEventListener("resize", updateScrollProgress);

/* Reveal animations */
const revealItems = document.querySelectorAll(".reveal-on-scroll");

if ("IntersectionObserver" in window) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add("is-visible");
                observer.unobserve(entry.target);
            }
        });
    }, {
        threshold: 0.16,
        rootMargin: "0px 0px -80px 0px"
    });

    revealItems.forEach((item) => revealObserver.observe(item));
} else {
    revealItems.forEach((item) => item.classList.add("is-visible"));
}

/* Dark and light mode */
const themeToggles = document.querySelectorAll(".theme-toggle");
const themeToggleLabels = document.querySelectorAll(".toggle-label");
let storedTheme = "light";

try {
    storedTheme = window.localStorage.getItem("canvaTipsTheme") || "light";
} catch (error) {
    storedTheme = "light";
}

function setTheme(theme) {
    const isDark = theme === "dark";
    document.body.dataset.theme = isDark ? "dark" : "light";

    themeToggles.forEach((toggle) => {
        toggle.setAttribute("aria-pressed", String(isDark));
        toggle.setAttribute("aria-label", getLocalizedText(isDark ? "Switch to light mode" : "Switch to dark mode"));
    });

    themeToggleLabels.forEach((label) => {
        label.textContent = getLocalizedText(isDark ? "Light" : "Dark");
    });

    try {
        window.localStorage.setItem("canvaTipsTheme", theme);
    } catch (error) {
        return;
    }
}

themeToggles.forEach((toggle) => {
    toggle.addEventListener("click", () => {
        const nextTheme = document.body.dataset.theme === "dark" ? "light" : "dark";
        setTheme(nextTheme);
    });
});

const languageToggle = document.querySelector(".language-toggle");

function updateCopyLabels() {
    document.querySelectorAll(".color-copy").forEach((label) => {
        const swatch = label.closest(".color-swatch");
        const labelKey = swatch && swatch.dataset.copied === "true" ? "Copied" : "Copy";
        label.textContent = getLocalizedText(labelKey);
    });
}

function updateLanguageToggle(language) {
    if (!languageToggle) {
        return;
    }

    const isPolish = language === "pl";
    languageToggle.setAttribute("aria-pressed", String(isPolish));
    languageToggle.setAttribute("aria-label", getLocalizedText(isPolish ? "Switch to English" : "Switch to Polish", language));
}

function setLanguage(language) {
    const nextLanguage = language === "pl" ? "pl" : "en";
    currentLanguage = nextLanguage;
    document.documentElement.lang = nextLanguage;
    document.body.dataset.language = nextLanguage;
    document.title = getLocalizedText("Canva Tips", nextLanguage);

    translatePageText(nextLanguage);
    updateLanguageToggle(nextLanguage);
    updateCopyLabels();
    setTheme(document.body.dataset.theme === "dark" || (!document.body.dataset.theme && storedTheme === "dark") ? "dark" : "light");

    try {
        window.localStorage.setItem("canvaTipsLanguage", nextLanguage);
    } catch (error) {
        return;
    }
}

setLanguage(currentLanguage);

if (languageToggle) {
    languageToggle.addEventListener("click", () => {
        setLanguage(currentLanguage === "pl" ? "en" : "pl");
    });
}

/* Subtle hero parallax */
const studio = document.querySelector(".presentation-studio");
const stage = document.querySelector(".studio-stage");

if (studio && stage && window.matchMedia("(prefers-reduced-motion: no-preference)").matches) {
    let animationFrame;

    studio.addEventListener("pointermove", (event) => {
        window.cancelAnimationFrame(animationFrame);

        animationFrame = window.requestAnimationFrame(() => {
            const rect = studio.getBoundingClientRect();
            const x = (event.clientX - rect.left) / rect.width - 0.5;
            const y = (event.clientY - rect.top) / rect.height - 0.5;
            stage.style.transform = `translate3d(${x * 10}px, ${y * 8}px, 0)`;
        });
    });

    studio.addEventListener("pointerleave", () => {
        stage.style.transform = "translate3d(0, 0, 0)";
    });
}
